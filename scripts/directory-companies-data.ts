/**
 * Empresas de Taiwán y Turquía del CSV `proveedores_taiwan_turquia.csv` y sus
 * líneas de producto. Las líneas salen del menú de productos del sitio oficial
 * de cada empresa (`fromSite: true`); si no se pudo leer un sitio, se usa la
 * actividad que informa el directorio (Kompass o Dalil). No hay precios, pedidos
 * mínimos, plazos ni fotos: esas empresas no los publican.
 */

export interface DirectoryProduct {
  readonly nameEn: string;
  readonly nameEs: string;
  /** Slug de la taxonomía de ProArq (puede ser un rubro principal si el producto es genérico). */
  readonly category: string;
  /** Página del producto si se conoce; si no, se usa el sitio de la empresa. */
  readonly pageUrl?: string;
}

export interface DirectoryCompany {
  /** Nombre exacto de la columna `empresa` del CSV. */
  readonly csvName: string;
  /** Ciudad en inglés si el CSV la trae en español. */
  readonly cityEn?: string;
  readonly activityEn: string;
  readonly activityEs: string;
  /** Sitio oficial verificado; null si no se encontró uno confiable. */
  readonly website: string | null;
  /** true si las líneas de producto se leyeron del sitio oficial. */
  readonly fromSite: boolean;
  readonly products: readonly DirectoryProduct[];
}

const p = (nameEn: string, nameEs: string, category: string, pageUrl?: string): DirectoryProduct => ({
  nameEn,
  nameEs,
  category,
  pageUrl,
});

